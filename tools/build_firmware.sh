#!/bin/bash
# Build Rusticc's MCU firmware (kaliru-mcu: firmware/ of the kaliru tree with the
# Rusticc patches, tools/kaliru-tree.sh) for COSMOS's boards
# into meta-rusticc's kalico-firmware-* bbappends (Yocto's rust has no
# bare-metal std and no xtensa: the images are built here, as ctr_check.sh
# builds them, and installed prebuilt; the toolchains: kaliru's
# firmware/README.md, the DSP's in its tests/ctr_check.sh):
#   recipes-apps/klipper/files/rusticc-firmware/<config>.bin   (stm32: flash image)
#   recipes-apps/klipper/files/rusticc-firmware/<config>.elf   (the DSP: remoteproc loads the ELF)
#   recipes-apps/klipper/rusticc-firmware.inc                  (RUSTICC_FW_REV: the images' revision)
#   bash tools/build_firmware.sh   (KALIRU=<tree>: another kaliru tree)
set -e
HERE=$(cd "$(dirname "$0")/.." && pwd)
cd "${KALIRU:-$HERE/work/kaliru}/firmware"
CARGO=${CARGO:-~/.cargo/bin/cargo}
OUT=$HERE/meta-rusticc/recipes-apps/klipper/files/rusticc-firmware
mkdir -p $OUT
for c in cosmos-cc1-bed cosmos-cc1-toolhead cosmos-cc1-canvas cosmos-cc2-bed cosmos-cc2-toolhead cosmos-cc2-canvas \
    cosmos-afc-lite-usb cosmos-cc1-dsp; do
    a=configs/$c/autoconf.h
    dir=~/rk/fwtarget-ctr-$c
    if grep -q "CONFIG_MACH_HIFI4 1" $a; then
        PATH=${XTENSA_GCC_BIN:-~/rk/xtensa/xtensa-nxp_rt700_hifi4_zephyr-elf/bin}:$PATH \
        KALIRU_MCU_CONFIG=configs/$c CARGO_TARGET_DIR=$dir $CARGO +esp build --profile mcu -Zjson-target-spec \
            -Z build-std=core,compiler_builtins -Z build-std-features=compiler-builtins-mem \
            --target $(pwd)/targets/xtensa-hifi4-none-elf.json
        cp $dir/xtensa-hifi4-none-elf/mcu/kaliru-mcu $OUT/$c.elf
    else
        if grep -q "CONFIG_MACH_STM32F1 1" $a; then target=thumbv7m-none-eabi; else target=thumbv7em-none-eabi; fi
        KALIRU_MCU_CONFIG=configs/$c CARGO_TARGET_DIR=$dir CARGO_PROFILE_MCU_OPT_LEVEL=s $CARGO build --profile mcu --target $target
        arm-none-eabi-objcopy -O binary $dir/$target/mcu/kaliru-mcu $OUT/$c.bin
    fi
    echo "== $c"
done
# (the firmware sources' content: the git tree of firmware/, the same
# however often kaliru-tree.sh recreates the commits; RUSTICC_FW_REV=<rev>
# where git can't read the tree)
rev=${RUSTICC_FW_REV:-$(git rev-parse --short HEAD:firmware)}
printf '# Autogenerated by tools/build_firmware.sh: the revision of the\n# prebuilt images in files/rusticc-firmware\nRUSTICC_FW_REV = "%s"\n' $rev \
    > $HERE/meta-rusticc/recipes-apps/klipper/rusticc-firmware.inc
ls -l $OUT
