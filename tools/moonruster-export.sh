#!/bin/bash
# Write the Rusticc patches back from the work tree
# (tools/moonruster-tree.sh): every commit on top of moonruster_git.bb's
# SRCREV becomes a patch in meta-rusticc/recipes-apps/moonruster/files/moonruster,
# and moonruster-patches.inc lists them for the recipe.
#   tools/moonruster-export.sh [SRC]
set -e
HERE=$(cd "$(dirname "$0")/.." && pwd)
R=$HERE/meta-rusticc/recipes-apps/moonruster
SRC=${1:-$HERE/work/moonruster}
rev=$(sed -n 's/^SRCREV = "\(.*\)"/\1/p' "$R/moonruster_git.bb")
mkdir -p "$R/files/moonruster"
rm -f "$R"/files/moonruster/*.patch
git -C "$SRC" format-patch -q --zero-commit --no-signature -o "$R/files/moonruster" "$rev"..HEAD
{
    echo "# Autogenerated by tools/moonruster-export.sh: Rusticc's patches to Moonruster"
    echo 'SRC_URI += " \'
    for p in "$R"/files/moonruster/*.patch; do echo "    file://moonruster/$(basename "$p") \\"; done
    echo '"'
} > "$R/moonruster-patches.inc"
ls "$R/files/moonruster"
