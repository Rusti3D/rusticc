#!/usr/bin/env python3
# The bitbake crate list of Rusticc's klippy (meta-rusticc's
# rusticc-crates.inc), from a kaliru checkout at rusticc_git.bb's SRCREV: every crates.io package of Cargo.lock as a crate://
# SRC_URI entry with its sha256, as cargo-bitbake writes it. (All of them,
# not only the ones this build's features use: cargo --frozen resolves the
# whole lock file.)
#   python3 tools/gen_crates_inc.py <kaliru> > meta-rusticc/recipes-apps/rusticc/rusticc-crates.inc
import sys
import tomllib
from pathlib import Path



def main():
    lock = tomllib.loads((Path(sys.argv[1]) / "Cargo.lock").read_text())
    pkgs = [p for p in lock["package"] if p.get("source", "").startswith("registry+")]
    pkgs.sort(key=lambda p: (p["name"], p["version"]))
    out = ["# Autogenerated by tools/gen_crates_inc.py from Cargo.lock", "", 'SRC_URI += " \\']
    for p in pkgs:
        out.append("    crate://crates.io/%s/%s \\" % (p["name"], p["version"]))
    out.append('"')
    out.append("")
    for p in pkgs:
        out.append('SRC_URI[%s-%s.sha256sum] = "%s"' % (p["name"], p["version"], p["checksum"]))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
