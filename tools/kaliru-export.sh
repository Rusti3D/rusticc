#!/bin/bash
# Write the Rusticc patches back from the work tree (tools/kaliru-tree.sh):
# every commit on top of rusticc_git.bb's SRCREV becomes a patch in
# meta-rusticc/recipes-apps/rusticc/files/kaliru, and rusticc-patches.inc
# lists them for the recipe.
#   tools/kaliru-export.sh [SRC]
set -e
HERE=$(cd "$(dirname "$0")/.." && pwd)
R=$HERE/meta-rusticc/recipes-apps/rusticc
SRC=${1:-$HERE/work/kaliru}
rev=$(sed -n 's/^SRCREV = "\(.*\)"/\1/p' "$R/rusticc_git.bb")
rm -f "$R"/files/kaliru/*.patch
git -C "$SRC" format-patch -q --zero-commit --no-signature -o "$R/files/kaliru" "$rev"..HEAD
{
    echo "# Autogenerated by tools/kaliru-export.sh: Rusticc's patches to kaliru"
    echo 'SRC_URI += " \'
    for p in "$R"/files/kaliru/*.patch; do echo "    file://kaliru/$(basename "$p") \\"; done
    echo '"'
} > "$R/rusticc-patches.inc"
ls "$R/files/kaliru"
