#!/usr/bin/env python3
# The Python code objects AFC.log names: AFC_logger writes the caller's
# "[file:function():co_firstlineno]" on every line, so the native AFC passes
# the same triple for each Python function it ports. Generated from the
# reference sources so no number is typed by hand.
#   afc_codes.py <afc_extras dir> [plugin .py ...] > src/extras/afc/codes.rs
# (plugins: AFC_ACE.py, the cosmoace_afc unit)
import ast
import pathlib
import re
import sys

MODULES = ["AFC", "AFC_functions", "AFC_lane", "AFC_unit", "AFC_extruder", "AFC_hub",
           "AFC_prep", "AFC_error", "AFC_spool", "AFC_stats", "AFC_assist", "AFC_utils",
           "AFC_logger", "AFC_respond", "AFC_canvas", "AFC_canvas_lane"]


def ident(*parts):
    s = "_".join(p for p in parts if p)
    return re.sub(r"[^A-Za-z0-9]", "_", s).upper()


def first_line(node):
    # co_firstlineno: the first decorator's line when there is one
    lines = [node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])]
    return min(lines)


def walk(node, module, fname, scope, out):
    for child in ast.iter_child_nodes(node):
        if isinstance(child, ast.ClassDef):
            walk(child, module, fname, scope + [child.name], out)
        elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.append((ident(module, *scope, child.name), fname, child.name, first_line(child)))
            walk(child, module, fname, scope + [child.name], out)
        elif isinstance(child, ast.Lambda):
            out.append((ident(module, *scope, "lambda", str(child.lineno)), fname, "<lambda>", child.lineno))
            walk(child, module, fname, scope, out)
        else:
            walk(child, module, fname, scope, out)


def main():
    src = pathlib.Path(sys.argv[1])
    print("// Generated by rusticc tools/afc_codes.py from the AFC sources: the")
    print("// (file, function, co_firstlineno) AFC.log prints for each python function.")
    print("use super::logger::Code;")
    print()
    seen = set()
    files = [src / (m + ".py") for m in MODULES] + [pathlib.Path(p) for p in sys.argv[2:]]
    for path in files:
        module, fname = path.stem, path.name
        tree = ast.parse(path.read_text())
        out = []
        walk(tree, module, fname, [], out)
        for name, f, func, line in out:
            if name in seen:
                # a property setter: same name, its own code object
                name = f"{name}_{line}"
            seen.add(name)
            print(f'pub const {name}: Code = Code {{ file: "{f}", func: "{func}", line: {line} }};')


main()
